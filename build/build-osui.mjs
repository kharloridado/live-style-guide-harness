#!/usr/bin/env node
/**
 * build-osui.mjs — compile the REAL OutSystems UI framework CSS, the base every specimen page
 * stacks dist/theme.css on, exactly as ODC stacks the Theme on the framework.
 *
 * Platform: project.config.json → environment picks the entry (ODC or O11). The two
 * entries differ in layout and pattern CSS, so measuring against the wrong one is drift.
 *
 * Re-run after updating the submodule:  npm run build:osui
 */
import * as sass from 'sass';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { projectConfig } from './lib/project-config.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLATFORM = projectConfig().environment === 'O11' ? 'O11' : 'ODC';
const ENTRY = resolve(root, `vendor/outsystems-ui/src/scss/${PLATFORM}.OutSystemsUI.scss`);
const OUT = resolve(root, 'review/vendor/outsystems-ui/outsystems-ui.css');

const banner =
	`/* GENERATED by build/build-osui.mjs — real OutSystems UI (${PLATFORM}) framework base.\n` +
	`   Source: vendor/outsystems-ui (submodule). Do not edit by hand; run \`npm run build:osui\`.\n` +
	`   The framework layer every specimen page loads BENEATH dist/theme.css. */\n`;

const { css } = sass.compile(ENTRY, { style: 'expanded', sourceMap: false, quietDeps: true });

// Drop Sass's leading `@charset "UTF-8";` — it must be the first byte to be valid, but
// our banner precedes it. Specimen pages declare <meta charset="utf-8">, so it's redundant.
const body = css.replace(/^@charset "UTF-8";\s*/i, '');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, banner + body);

console.log(`build:osui → ${OUT.replace(root + '\\', '').replace(root + '/', '')}  (${(banner.length + css.length) / 1024 | 0} KB)`);
